"""Generate every number in the paper directly from results/*.json.

No figure caption, table cell, or inline statistic in main.tex is typed by hand.
Each is either \\input from paper/generated/ or expanded from a macro defined in
paper/generated/macros.tex. That removes the failure mode this repository has
already had once: prose asserting a finding that no run produced.

    python paper/make_tables.py --dataset squad
    python paper/make_tables.py --dataset squad --dry-run --allow-synthetic

Refuses to emit from synthetic (dry-run) results unless --allow-synthetic is given,
and stamps a visible SYNTHETIC banner into the output when it is.
"""

import argparse
import json
import os
import sys

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import config
from utils.stats import rate_with_ci_clustered

OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "generated")


def load(name):
    path = os.path.join(config.RESULTS_DIR, name)
    if not os.path.exists(path):
        return None
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def pct(v, digits=1):
    return "--" if v is None else f"{100 * v:.{digits}f}"


def ci(c, digits=1):
    """Format a {mean, lo, hi} block as `mean [lo, hi]` in percent."""
    if not c or c.get("mean") is None:
        return "--"
    return (f"{100 * c['mean']:.{digits}f} "
            f"\\tiny[{100 * c['lo']:.{digits}f}, {100 * c['hi']:.{digits}f}]")


def esc(s):
    return str(s).replace("_", "\\_").replace("%", "\\%").replace("&", "\\&")


# --------------------------------------------------------------------------- #

def valid_rows(data, cond):
    rows = (data.get("rows") or {}).get(cond) or []
    return [r for r in rows if r.get("outcome") not in (None, "INVALID")]


def grounded_ci(data, cond):
    """CI for incorrect-but-grounded answers, recomputed from per-item rows
    (the run summaries store a point estimate only)."""
    rows = valid_rows(data, cond)
    if not rows:
        return None
    return rate_with_ci_clustered(rows, lambda r: r["outcome"] == "INCORRECT_GROUNDED")


def table_noise(data):
    """Table 1 — outcome composition across noise conditions."""
    if not data:
        return None
    conds = data["conditions"]
    order = ["clean"] + [c for c in conds if c != "clean"]

    lines = [
        "% Auto-generated by paper/make_tables.py — do not edit.",
        "\\begin{table*}[t]\\centering\\small",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{lrrrrrr}",
        "\\toprule",
        "Condition & Correct & Abstained & Unsupported & Grounded err. & Silent-fail & $\\Delta$F1 vs clean \\\\",
        "\\midrule",
    ]
    for name in order:
        s = conds.get(name, {})
        c = s.get("ci", {})
        vs = (s.get("vs_clean") or {}).get("F1")
        delta = "--" if not vs else (
            f"{vs['diff']:+.3f} \\tiny[{vs['lo']:+.3f}, {vs['hi']:+.3f}]")
        grounded = grounded_ci(data, name)
        lines.append(
            f"{esc(name)} & {ci(c.get('correct_rate'))} & {ci(c.get('abstention_rate'))} "
            f"& {ci(c.get('hallucination_rate'))} & {ci(grounded)} "
            f"& {ci(c.get('silent_failure_rate'))} "
            f"& {delta} \\\\"
        )
    lines += [
        "\\bottomrule", "\\end{tabular}}",
        "\\caption{Outcome composition under each retrieval perturbation at $K=4$. "
        "All values are percentages with 95\\% bootstrap confidence intervals; "
        "$\\Delta$F1 is a paired bootstrap against the clean condition on the same "
        "questions. Grounded err.\\ is a wrong answer that is faithful to the "
        "(corrupted) context; Unsupported is an assertion the context does not "
        "support. Silent-fail is the share of non-correct answers that were "
        "assertions rather than abstentions.}",
        "\\label{tab:noise}", "\\end{table*}",
    ]
    return "\n".join(lines)


XMODEL_CONDS = ["clean", "related@75", "related@100", "random@100",
                "counterfactual@50", "counterfactual@100"]


def table_crossmodel(primary, second):
    """Table 3 - the primary generator next to the cross-family replication."""
    if not (primary and second):
        return None
    gens = [(primary["manifest"].get("llm_model", "?"), primary),
            (second["manifest"].get("llm_model", "?"), second)]
    lines = [
        "% Auto-generated by paper/make_tables.py — do not edit.",
        "\\begin{table}[t]\\centering\\small",
        "\\resizebox{\\columnwidth}{!}{%",
        "\\begin{tabular}{llrrrr}",
        "\\toprule",
        "Generator & Condition & Correct & Abstained & Unsupported & Grounded err. \\\\",
        "\\midrule",
    ]
    for gi, (model, data) in enumerate(gens):
        conds = data["conditions"]
        for i, name in enumerate(XMODEL_CONDS):
            c = (conds.get(name) or {}).get("ci", {})
            g = grounded_ci(data, name)
            label = esc(model.replace("models/", "")) if i == 0 else ""
            lines.append(
                f"{label} & {esc(name)} & {pct_ci(c.get('correct_rate'))} & "
                f"{pct_ci(c.get('abstention_rate'))} & {pct_ci(c.get('hallucination_rate'))} & "
                f"{pct_ci(g)} \\\\")
        if gi == 0:
            lines.append("\\midrule")
    lines += [
        "\\bottomrule", "\\end{tabular}}",
        "\\caption{Cross-family replication on the same 150 questions, retrieval and "
        "perturbations. Percentages; the second generator is an open-weights model "
        "from a different family. Judge and scoring are identical.}",
        "\\label{tab:xmodel}", "\\end{table}",
    ]
    return "\n".join(lines)


def pct_ci(c):
    """Point estimate only, for the compact cross-model table."""
    if not c or c.get("mean") is None:
        return "--"
    return f"{100 * c['mean']:.1f}"


def crossmodel_macros(second):
    """Headline numbers for the replication, with a Two suffix."""
    out = []
    if not second:
        return out
    def m(name, value):
        return f"\\newcommand{{\\{name}}}{{{value}}}"
    man = second.get("manifest", {})
    out.append(m("genModelTwo", esc(man.get("llm_model", "??"))))
    out.append(m("judgeModelTwo", esc(man.get("judge_model", "??"))))
    conds = second.get("conditions", {})
    comps = [n for n in conds if n != "clean"]
    out.append(m("nCondTwo", len(comps)))
    up = down = 0
    bound = 0.0
    for n in comps:
        h = ((conds[n].get("vs_clean") or {}).get("hallucination_rate") or {})
        if h.get("significant_fdr"):
            if h["diff"] > 0: up += 1
            else: down += 1
        else:
            bound = max(bound, abs(h.get("lo", 0)), abs(h.get("hi", 0)))
    out += [m("halluUpTwo", up), m("halluDownTwo", down),
            m("halluNullTwo", len(comps) - up - down),
            m("halluBoundTwo", f"{100 * bound:.1f}")]
    def p_str(pv):
        return "< 0.0001" if pv is not None and pv < 1e-4 else f"= {pv:.3f}"
    cf = (conds.get("counterfactual@50") or {}).get("vs_clean") or {}
    for key, tag in (("correct_rate", "Correct"), ("abstention_rate", "Abstain"),
                     ("incorrect_grounded_rate", "Grounded"), ("hallucination_rate", "Hallu")):
        d = cf.get(key)
        if d and d.get("diff") is not None:
            out += [m(f"cfDelta{tag}Two", f"{100 * d['diff']:+.1f}"),
                    m(f"cfQ{tag}Two", p_str(d.get("q_value")))]
    g0, g1 = grounded_ci(second, "clean"), grounded_ci(second, "counterfactual@50")
    if g0 and g1:
        out += [m("groundedCleanTwo", f"{100 * g0['mean']:.1f}"),
                m("groundedCFTwo", f"{100 * g1['mean']:.1f}")]
    for name, tag in (("related@100", "Related"), ("random@100", "Random")):
        c = (conds.get(name) or {}).get("ci", {}).get("abstention_rate")
        if c and c.get("mean") is not None:
            out.append(m(f"abstainAt{tag}Two", f"{100 * c['mean']:.0f}"))
    n_inv = sum(cc.get("n_invalid", 0) for cc in conds.values())
    out.append(m("nInvalidTwo", n_inv))
    return out


def table_predictability(data):
    """Table 2 — pre-generation failure prediction."""
    if not data:
        return None
    lines = [
        "% Auto-generated by paper/make_tables.py — do not edit.",
        "\\begin{table}[t]\\centering\\small",
        "\\begin{tabular}{llrr}",
        "\\toprule",
        "Target & Signal & AUROC & Base rate \\\\",
        "\\midrule",
    ]
    for target, block in data.get("targets", {}).items():
        base = block.get("base_rate")
        for i, (signal, auroc) in enumerate(block.get("auroc", {}).items()):
            lines.append(
                f"{esc(target) if i == 0 else ''} & {esc(signal)} & "
                f"{'--' if auroc is None else f'{auroc:.3f}'} & "
                f"{'' if i else pct(base) + '\\%'} \\\\"
            )
        lines.append("\\midrule")
    lines[-1] = "\\bottomrule"
    lines += [
        "\\end{tabular}",
        "\\caption{AUROC of retrieval-side signals available \\emph{before} the "
        "generator is called. \\textsc{any\\_failure} is any non-correct answer; "
        "\\textsc{silent\\_wrong} is an unsupported assertion. 0.5 is chance.}",
        "\\label{tab:predict}", "\\end{table}",
    ]
    return "\n".join(lines)


def macros(baseline, noise, predict, manifest, synthetic, judge=None,
           mitig=None, manip=None):
    """Inline numbers, so prose can never drift from the data."""
    def m(name, value):
        return f"\\newcommand{{\\{name}}}{{{value}}}"

    out = ["% Auto-generated by paper/make_tables.py — do not edit."]
    if synthetic:
        out.append("\\newcommand{\\SYNTHETICRESULTS}{}  % results are dry-run stubs")

    if manifest:
        out += [
            m("nQA", manifest.get("n_qa", "??")),
            m("nAnswerable", manifest.get("n_answerable", "??")),
            m("nUnanswerable", manifest.get("n_unanswerable", "??")),
            m("genModel", esc(manifest.get("llm_model", "??"))),
            # The baseline and the perturbation/mitigation phases were judged by
            # different checkpoints; report both rather than whichever loaded first.
            m("judgeModelBaseline", esc(manifest.get("judge_model", "??"))),
            m("judgeModel", esc(((noise or {}).get("manifest") or manifest).get("judge_model", "??"))),
            m("embedModel", esc(manifest.get("embed_model", "??"))),
            m("randomSeed", manifest.get("seed", "??")),
        ]

    if baseline:
        s = baseline["summary"]
        out += [
            m("baseF", pct(s.get("F1"))),
            m("baseEM", pct(s.get("EM"))),
            m("baseAbstain", pct(s.get("abstention_rate"))),
            m("baseHallucUnans", pct(s.get("hallucination_rate_unanswerable"))),
            m("baseGoldInCtx", pct(s.get("gold_in_context_rate"))),
            m("baseParametric", pct(s.get("parametric_correct_rate"))),
            m("baseSilentFail", pct(s.get("silent_failure_rate"))),
        ]

    if noise:
        conds = noise["conditions"]
        # Headline numbers for the abstract: the accuracy drop the manipulation
        # produced, and the bound on the hallucination null it did not.
        # Read the fraction from the condition name rather than the summary field.
        # A results file rebuilt from checkpoints may not carry noise_frac, and
        # defaulting it to 0 silently selects the *mildest* condition -- which would
        # put the 25% accuracy drop in an abstract that describes the 75% range.
        def _frac(name):
            try:
                return int(name.split("@")[1])
            except (IndexError, ValueError):
                return -1

        # Two regimes need separate numbers. Through partial corruption the
        # hallucination rate is flat; at total corruption it falls while abstention
        # jumps. Collapsing them into one "worst condition" figure would put a
        # decrease behind a symmetric +/- bound and misdescribe the result.
        # Counterfactual is the condition that carries the paper: evidence present
        # but false. Its numbers are needed separately from the absent-evidence
        # regimes, because the two produce opposite failure modes.
        for label, cond in (("Partial", "related@75"), ("Total", "related@100"),
                            ("CF", "counterfactual@50")):
            if cond not in conds:
                continue
            vs = conds[cond].get("vs_clean") or {}
            d_corr = vs.get("correct_rate") or vs.get("F1")
            d_hall = vs.get("hallucination_rate")
            d_abst = vs.get("abstention_rate")
            if d_corr and d_corr.get("diff") is not None:
                out.append(m(f"deltaCorrect{label}", f"{abs(100 * d_corr['diff']):.1f}"))
            if d_hall and d_hall.get("hi") is not None:
                out.append(m(f"halluBound{label}",
                             f"{100 * max(abs(d_hall['lo']), abs(d_hall['hi'])):.1f}"))
                out.append(m(f"deltaHallu{label}", f"{100 * d_hall['diff']:+.1f}"))
            if d_abst and d_abst.get("diff") is not None:
                out.append(m(f"deltaAbstain{label}", f"{100 * d_abst['diff']:+.1f}"))
            if conds[cond].get("ci", {}).get("abstention_rate", {}).get("mean") is not None:
                out.append(m(f"abstainAt{label}",
                             f"{100 * conds[cond]['ci']['abstention_rate']['mean']:.0f}"))
            d_ground = vs.get("incorrect_grounded_rate")
            if d_ground and d_ground.get("diff") is not None:
                out.append(m(f"deltaGrounded{label}", f"{abs(100 * d_ground['diff']):.1f}"))

        curve = [(f, conds.get(f"related@{int(f * 100)}", {}).get("silent_failure_rate"))
                 for f in (0.25, 0.5, 0.75, 1.0)]
        curve = [(f, v) for f, v in curve if v is not None]
        if curve:
            peak_f, peak_v = max(curve, key=lambda x: x[1])
            interior = peak_f not in (curve[0][0], curve[-1][0])
            out += [
                m("peakNoiseFrac", f"{int(peak_f * 100)}"),
                m("peakSilentFail", pct(peak_v)),
                # Consumed by \ifdefined in main.tex so the H1 sentence is written
                # by the data rather than by the author's expectation.
                m("HOneSupported", "true" if interior else "false"),
            ]

    if predict:
        for target, block in predict.get("targets", {}).items():
            tag = "Any" if target == "any_failure" else "Silent"
            out += [
                m(f"best{tag}Signal", esc(block.get("best_signal", "--"))),
                m(f"best{tag}AUROC",
                  "--" if block.get("best_auroc") is None else f"{block['best_auroc']:.3f}"),
            ]


    if noise:
        g = grounded_ci(noise, "clean")
        if g:
            out.append(m("groundedClean", f"{100 * g['mean']:.1f}"))
        g = grounded_ci(noise, "counterfactual@50")
        if g:
            out.append(m("groundedCF", f"{100 * g['mean']:.1f}"))
        cf = (noise.get("conditions") or {}).get("counterfactual@50", {}).get("ci", {}).get("correct_rate")
        if cf and cf.get("mean") is not None:
            out.append(m("correctCF", f"{100 * cf['mean']:.1f}"))

    if mitig:
        conds = mitig.get("conditions", {})
        base, strict = conds.get("none") or {}, conds.get("strict_prompt") or {}
        vs = strict.get("vs_none") or {}
        n = base.get("n")
        if n and base.get("hallucination_rate") is not None:
            out += [
                m("mitNUnsupNone", round(n * base["hallucination_rate"])),
                m("mitNUnsupStrict", round(n * strict["hallucination_rate"])),
                m("mitNCorrectNone", round(n * base["ci"]["correct_rate"]["mean"])),
                m("mitNCorrectStrict", round(n * strict["ci"]["correct_rate"]["mean"])),
                m("mitCorrectNonePct", f"{100 * base['ci']['correct_rate']['mean']:.1f}"),
            ]
            lost = round(n * base["ci"]["correct_rate"]["mean"]) - round(n * strict["ci"]["correct_rate"]["mean"])
            saved = round(n * base["hallucination_rate"]) - round(n * strict["hallucination_rate"])
            if saved > 0:
                out.append(m("mitCorrectPerFabrication", f"{lost / saved:.1f}"))
        for key, tag in (("hallucination_rate", "Hallu"), ("abstention_rate", "Abstain"),
                         ("correct_rate", "Correct"), ("incorrect_grounded_rate", "Grounded")):
            d = vs.get(key)
            if d and d.get("diff") is not None:
                pv = d.get("p_two_sided")
                out += [m(f"mitDelta{tag}", f"{d['diff']:+.3f}"),
                        m(f"mitP{tag}", "< 0.0001" if pv is not None and pv < 1e-4 else f"= {pv:.3f}")]

    if manip:
        cv = manip.get("convergent_validity") or {}
        nat, syn = cv.get("natural_fail") or {}, cv.get("synthetic") or {}
        if nat.get("n"):
            out += [
                m("manipNNatural", nat["n"]),
                m("manipAbstainNatural", f"{nat['ABSTAIN']['mean']:.2f}"),
                m("manipAbstainSynthetic", f"{syn['ABSTAIN']['mean']:.2f}"),
                m("manipUnsupNatural", f"{nat['UNSUPPORTED']['mean']:.2f}"),
                m("manipUnsupSynthetic", f"{syn['UNSUPPORTED']['mean']:.2f}"),
            ]

    if judge:
        dep = judge.get("dependence") or {}
        if dep.get("n_valid"):
            out.append(m("nScoredRows", f"{dep['n_valid']:,}"))
            out.append(m("judgeInvocationPct", f"{100 * dep['judge_invocation_rate']:.1f}"))
            out.append(m("nUnsupported", dep.get("n_unsupported", "??")))
            out.append(m("nUnsupportedRule", dep.get("n_unsupported_rule", "??")))
            out.append(m("nUnsupportedJudged", dep.get("n_unsupported_judged", "??")))
            share = dep.get("judge_derived_share_of_headline")
            if share is not None:
                out.append(m("ruleDerivedPct", f"{100 * (1 - share):.0f}"))
        agree = judge.get("agreement") or {}
        if agree.get("n"):
            out.append(m("judgeAgreementN", agree["n"]))
            out.append(m("judgeB", esc(agree.get("judge_b", "??"))))
            out.append(m("judgeRawAgree", f"{100 * agree['raw_agreement']:.1f}"))
            if agree.get("cohens_kappa") is not None:
                out.append(m("judgeKappa", f"{agree['cohens_kappa']:.2f}"))
            conf = agree.get("confusion") or {}
            # Agreement on the rare class is what matters for the headline metric;
            # kappa on an 80/5 split is unstable and raw agreement is dominated by
            # the majority label.
            for lab, tag in (("UNSUPPORTED", "Unsup"), ("SUPPORTED", "Sup")):
                row = conf.get(lab) or {}
                n_a = sum(row.values())
                if n_a:
                    out.append(m(f"judgeA{tag}N", n_a))
                    out.append(m(f"judgeA{tag}Agree", row.get(lab, 0)))

    return "\n".join(out)


# --------------------------------------------------------------------------- #

def main():
    p = argparse.ArgumentParser(description="Generate paper tables and macros")
    p.add_argument("--dataset", default="squad", choices=["squad", "hotpot"])
    p.add_argument("--dry-run", action="store_true", help="Read results_dryrun/")
    p.add_argument("--allow-synthetic", action="store_true",
                   help="Permit generation from dry-run results (marks output SYNTHETIC)")
    args = p.parse_args()
    config.set_dry_run(args.dry_run)

    judge = load(f"phase6_judge_agreement_{args.dataset}.json")
    baseline = load(f"phase1_baseline_{args.dataset}.json")
    noise = load(f"phase2b_noise_{args.dataset}.json")
    predict = load(f"phase3_predictability_{args.dataset}.json")
    mitig = load(f"phase4_fixes_{args.dataset}.json")
    manip = load(f"phase5_manipulation_check_{args.dataset}.json")
    second = load(f"phase2b_noise_{args.dataset}_gemma.json")
    if second and not second.get("manifest", {}).get("grid_complete"):
        print("  cross-model results incomplete; skipping Table 3")
        second = None

    if not any((baseline, noise, predict)):
        sys.exit(f"No results for '{args.dataset}' in {config.RESULTS_DIR}. "
                 f"Run the phases first.")

    manifest = (baseline or noise or {}).get("manifest", {})
    synthetic = bool(manifest.get("synthetic"))
    if synthetic and not args.allow_synthetic:
        sys.exit("Refusing to build paper tables from synthetic dry-run results.\n"
                 "Run the real pipeline, or pass --allow-synthetic to preview the layout.")

    os.makedirs(OUT_DIR, exist_ok=True)
    written = []
    for filename, content in (
        ("tab1_noise.tex", table_noise(noise)),
        ("tab2_predictability.tex", table_predictability(predict)),
        ("tab3_crossmodel.tex", table_crossmodel(noise, second)),
        ("macros.tex", "\n".join([macros(baseline, noise, predict, manifest, synthetic,
                                          judge, mitig, manip)] + crossmodel_macros(second))),
    ):
        if content is None:
            print(f"  skip {filename} (source results missing)")
            continue
        path = os.path.join(OUT_DIR, filename)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content + "\n")
        written.append(filename)
        print(f"  wrote paper/generated/{filename}")

    if synthetic:
        print("\n*** Output built from SYNTHETIC results. Not submittable. ***")
    print(f"\n{len(written)} file(s) generated. Build with: "
          f"cd paper && pdflatex main && bibtex main && pdflatex main && pdflatex main")


if __name__ == "__main__":
    main()
